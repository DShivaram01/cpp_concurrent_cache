#!/usr/bin/env bash
# Controlled benchmark: RUNS identical runs of every workload x thread count,
# raw output of each run kept, summary reports the median per configuration.
#
# Usage: ./scripts/run_benchmark_suite.sh [cache_benchmark args, e.g. --ops 1000000]
# Env:   RUNS=5        number of runs
#        CPU_LIST=0-7  CPUs to pin to with taskset (default: first min(nproc, 8))
# Run it on an idle machine, not a shared login node.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${ROOT_DIR}/build"
RESULTS_DIR="${ROOT_DIR}/results"
RAW_DIR="${RESULTS_DIR}/raw"
SUMMARY="${RESULTS_DIR}/summary.md"
RUNS="${RUNS:-5}"

cmake -S "${ROOT_DIR}" -B "${BUILD_DIR}" -DCMAKE_BUILD_TYPE=Release > /dev/null
cmake --build "${BUILD_DIR}" --target cache_benchmark -j

PIN=()
PINNING="none (taskset not available)"
if command -v taskset > /dev/null; then
    CPUS="$(nproc)"
    CPU_LIST="${CPU_LIST:-0-$(( (CPUS < 8 ? CPUS : 8) - 1 ))}"
    PIN=(taskset -c "${CPU_LIST}")
    PINNING="taskset -c ${CPU_LIST}"
fi

LOAD_AVG="$(cut -d' ' -f1-3 /proc/loadavg 2> /dev/null || echo unknown)"
mkdir -p "${RAW_DIR}"
rm -f "${RAW_DIR}"/run_*.txt  # raw/ must match the summary written below
for ((i = 1; i <= RUNS; i++)); do
    echo "run ${i}/${RUNS}"
    ${PIN[@]+"${PIN[@]}"} "${BUILD_DIR}/cache_benchmark" "$@" > "${RAW_DIR}/run_${i}.txt"
done

field() { sed -n "s|^$1: *||p" "${RAW_DIR}/run_1.txt"; }
FLAGS="$(sed -n 's/^CMAKE_CXX_FLAGS_RELEASE:STRING=//p' "${BUILD_DIR}/CMakeCache.txt")"

{
    echo "# Benchmark summary"
    echo
    echo "Median of ${RUNS} runs per configuration (not the best run). Every run's raw output is in [\`raw/\`](raw/)."
    echo "Generated by \`scripts/run_benchmark_suite.sh $*\`."
    echo
    echo "| | |"
    echo "|---|---|"
    echo "| Date (UTC) | $(date -u '+%Y-%m-%d %H:%M') |"
    echo "| CPU | $(field cpu) |"
    echo "| Hardware threads | $(field 'hardware threads') |"
    echo "| Compiler | $(field compiler) |"
    echo "| Build | $(field 'build type'), \`${FLAGS}\` |"
    echo "| Pinning | ${PINNING} |"
    echo "| Load average before runs | ${LOAD_AVG} |"
    echo "| Kernel | $(uname -sr) |"
    echo "| Workload | $(field 'total ops/run') ops per run, capacity $(field 'cache capacity'), key space $(field 'key space'), value size $(field 'value size') |"

    awk '
        function sortnum(s, v,    n, i, j, x) {
            n = split(s, v, " ")
            for (i = 1; i <= n; i++) v[i] += 0
            for (i = 2; i <= n; i++) {
                x = v[i]
                for (j = i - 1; j > 0 && v[j] > x; j--) v[j + 1] = v[j]
                v[j + 1] = x
            }
            return n
        }
        function med(v, n) { return n % 2 ? v[(n + 1) / 2] : (v[n / 2] + v[n / 2 + 1]) / 2 }
        function median(s,    v, n) { n = sortnum(s, v); return med(v, n) }

        FNR == 1 { w = "" }
        /get \/ [0-9]+% put\)$/ { w = $0; if (!(w in seen)) { seen[w] = 1; order[++nw] = w }; next }
        w != "" && NF == 8 && $1 ~ /^[0-9]+$/ {
            k = w SUBSEP $1
            if (!(k in ops)) threads[w] = threads[w] " " $1
            ops[k] = ops[k] " " $3; p50[k] = p50[k] " " $5; p95[k] = p95[k] " " $6; p99[k] = p99[k] " " $7
        }
        END {
            for (i = 1; i <= nw; i++) {
                w = order[i]
                printf "\n## %s\n\n", w
                print "| Threads | ops/sec (median) | ops/sec (min - max) | p50 ns | p95 ns | p99 ns |"
                print "|---:|---:|---:|---:|---:|---:|"
                n = split(threads[w], t, " ")
                for (j = 1; j <= n; j++) {
                    k = w SUBSEP t[j]
                    m = sortnum(ops[k], v)
                    printf "| %d | %.0f | %.0f - %.0f | %.0f | %.0f | %.0f |\n",
                        t[j], med(v, m), v[1], v[m], median(p50[k]), median(p95[k]), median(p99[k])
                }
            }
        }
    ' "${RAW_DIR}"/run_*.txt
} > "${SUMMARY}"

echo "Saved ${RAW_DIR}/run_*.txt and ${SUMMARY}"
